bool isValidEmailFormat(String email) {
  return _emailPattern.hasMatch(email.trim());
}

bool isDisposableEmail(String email) {
  final trimmed = email.trim().toLowerCase();
  if (!isValidEmailFormat(trimmed)) return false;
  final domain = trimmed.split('@').last;
  if (_disposableDomains.contains(domain)) return true;
  return _suspiciousTokens.any(domain.contains);
}
